        internal static bool TryEstimateGpwPercentage(int millivolts, bool charging, out int level)
        {
            level = -1;
            if (millivolts < 2800 || millivolts > 4500) return false;
            double value;
            if (charging)
            {
                // Official time-slot model needs stable-voltage/history tracking. Without it,
                // assigning a percentage on the 4.2V plateau would invent a reading.
                if (millivolts < Charge[0].Mv || millivolts >= 4200) return false;
                value = Interpolate(Charge, millivolts);
            }
            else
            {
                value = 100.0 * (1.0 - Interpolate(Discharge, millivolts) / 90234.0);
            }
            level = Math.Clamp((int)Math.Round(value, MidpointRounding.AwayFromZero), 0, 100);
            return true;
        }

        private static double Interpolate((int Mv, int Value)[] points, int mv)
        {
            if (mv <= points[0].Mv) return points[0].Value;
            if (mv >= points[^1].Mv) return points[^1].Value;
            int low = 0, high = points.Length - 1;
            while (high - low > 1)
            {
                int middle = (low + high) / 2;
                if (points[middle].Mv <= mv) low = middle;
                else high = middle;
            }
            var left = points[low]; var right = points[high];
            return left.Value + (right.Value - left.Value) * (double)(mv - left.Mv) / (right.Mv - left.Mv);
        }
